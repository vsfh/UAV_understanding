def main() -> None:
    parser = argparse.ArgumentParser(description="Build a staged CLEAR-UAV result report")
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    output_dir = args.output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    labels = [
        line.strip()
        for line in (PROJECT_ROOT / "configs/core18_complete.txt").read_text().splitlines()
        if line.strip() and not line.startswith("#")
    ]
    generated_at = datetime.now(timezone.utc).replace(microsecond=0).isoformat()
    files: list[str] = []
    quality: dict[str, dict] = {}
    main_comparison = []

    for protocol in PROTOCOLS:
        for method, relative in MAIN_METHODS:
            path, result = load_result(relative, protocol)
            relative_path = path.relative_to(PROJECT_ROOT).as_posix()
            files.append(relative_path)
            checks = validate_result(path, result, len(labels))
            quality[relative_path] = checks
            metrics = pair_metrics(result)
            main_comparison.append(
                {
                    "protocol": protocol,
                    "method": method,
                    "macro_f1": metrics["macro_f1"],
                    "micro_f1": metrics["micro_f1"],
                    "worst_class_recall": metrics["worst_class_recall"],
                    "num_samples": checks["num_samples"],
                    "observed_classes": checks["observed_classes"],
                    "dominant_share": checks["dominant_share"],
                }
            )

    view_ablation = []
    for view, relative in (
        ("pair", "qwen/lora"),
        ("crop-only", "qwen/label_crop"),
        ("context-only", "qwen/label_context"),
    ):
        path, result = load_result(relative, "session_disjoint")
        relative_path = path.relative_to(PROJECT_ROOT).as_posix()
        if relative_path not in files:
            files.append(relative_path)
        checks = validate_result(path, result, len(labels))
        quality[relative_path] = checks
        metrics = result["metrics"]
        view_ablation.append(
            {
                "view": view,
                "pair_macro_f1": metrics["pair"]["macro_f1"],
                "pair_micro_f1": metrics["pair"]["micro_f1"],
                "set_macro_f1": metrics["set_union"]["macro_f1"],
                "set_micro_f1": metrics["set_union"]["micro_f1"],
                "parse_failure_rate": checks["parse_failure_rate"],
                "num_samples": checks["num_samples"],
            }
        )

    openclip_deltas = []
    for protocol in PROTOCOLS:
        _, linear = load_result("openclip/linear_probe", protocol)
        _, full = load_result("openclip/full_finetune", protocol)
        openclip_deltas.append(
            {
                "protocol": protocol,
                **{
                    metric: full["metrics"][metric] - linear["metrics"][metric]
                    for metric in (
                        "macro_f1",
                        "micro_f1",
                        "mean_average_precision",
                        "hard_negative_accuracy",
                        "aurc",
                    )
                },
            }
        )

    summary = {
        "generated_at": generated_at,
        "scope": {"split": "val", "seed": 43, "configured_labels": len(labels)},
        "files": sorted(files),
        "quality": quality,
        "main_comparison": main_comparison,
        "view_ablation": view_ablation,
        "openclip_full_minus_linear": openclip_deltas,
        "missing_stage_results": [
            "GeoChat direct prompt",
            "GeoChat definition prompt",
            "Qwen zero-shot direct/definition baselines",
            "test split",
            "multi-seed variance",
        ],
    }
    artifact = build_artifact(summary, generated_at)
    (output_dir / "analysis_summary.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    for filename, rows in (
        ("main_comparison.csv", main_comparison),
        ("view_ablation.csv", view_ablation),
    ):
        with (output_dir / filename).open("w", encoding="utf-8", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
            writer.writeheader()
            writer.writerows(rows)
    (output_dir / "artifact.json").write_text(
        json.dumps(artifact, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(output_dir / "artifact.json")


if __name__ == "__main__":
    main()
