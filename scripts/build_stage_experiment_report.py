PROJECT_ROOT = Path(__file__).resolve().parents[1]
RESULTS_ROOT = PROJECT_ROOT / "results"
DEFAULT_OUTPUT = PROJECT_ROOT / "reports/stage_experiment_2026-08-20"
PROTOCOLS = ("forward_temporal", "session_disjoint", "unseen_site")
MAIN_METHODS = (
    ("OpenCLIP linear probe", "openclip/linear_probe"),
    ("OpenCLIP full FT", "openclip/full_finetune"),
    ("Qwen pair LoRA", "qwen/lora"),
)


def load_result(relative: str, protocol: str) -> tuple[Path, dict]:
    path = RESULTS_ROOT / relative / protocol / "seed43_val.json"
    if not path.is_file():
        raise FileNotFoundError(path)
    return path, json.loads(path.read_text(encoding="utf-8"))


def pair_metrics(result: dict) -> dict:
    metrics = result["metrics"]
    return metrics["pair"] if "pair" in metrics else metrics


def validate_result(path: Path, result: dict, expected_labels: int) -> dict:
    rows = result["rows"]
    if result["num_samples"] != len(rows):
        raise ValueError(f"num_samples disagrees with row count: {path}")
    if len({row["record_uid"] for row in rows}) != len(rows):
        raise ValueError(f"record_uid is not unique: {path}")
    if any(len(row["scores"]) != expected_labels for row in rows):
        raise ValueError(f"score vectors are not {expected_labels}-class complete: {path}")

    targets = Counter(row["target"] for row in rows)
    parse_failures = sum(not row["prediction"] for row in rows)
    dominant_label, dominant_count = targets.most_common(1)[0]
    return {
        "num_samples": len(rows),
        "observed_classes": len(targets),
        "dominant_label": dominant_label,
        "dominant_share": dominant_count / len(rows),
        "parse_failures": parse_failures,
        "parse_failure_rate": parse_failures / len(rows),
    }


def source_spec(
    source_id: str,
    label: str,
    csv_path: str,
    columns: list[str],
    result_paths: list[str],
    generated_at: str,
) -> dict:
    return {
        "id": source_id,
        "label": label,
        "path": csv_path,
        "query": {
            "engine": "DuckDB",
            "language": "sql",
            "sql": f"SELECT {', '.join(columns)} FROM read_csv_auto('{csv_path}')",
            "description": (
                "Reads the validated report dataset generated by "
                "scripts/build_stage_experiment_report.py."
            ),
            "executed_at": generated_at,
            "tables_used": [csv_path, *result_paths],
            "filters": ["split = val", "seed = 43", "labels = core18_complete"],
            "metric_definitions": [
                "Macro-F1: unweighted mean of per-class F1 across the configured 18 labels.",
                "Micro-F1: F1 after pooling true positives, false positives, and false negatives.",
                "Set-union F1: classification F1 after unioning targets and predictions by content group.",
                "mAP: mean per-class average precision from continuous score rankings.",
                "Hard-negative accuracy: fraction of ontology-neighbor comparisons where the true label scores higher.",
                "AURC: average risk as predictions are included from highest to lowest confidence; lower is better.",
            ],
        },
    }


